#!/bin/bash
# SSH登录警告：/home目录磁盘使用率超过95%提醒

# 核心：获取/home目录的磁盘使用率（纯数字，去掉%）
DISK_USAGE=$(df -h /home | tail -n 1 | awk '{print $5}' | tr -d '%')

# 告警阈值（可自行修改，比如90、98）
THRESHOLD=95

# 判断并输出警告（红色字体，醒目）
if [ "$DISK_USAGE" -gt "$THRESHOLD" ]; then
    echo -e "\033[31m===============================================================\033[0m"
    echo -e "\033[31m⚠️  系统警告：/home 目录磁盘空间严重不足！\033[0m"
    echo -e "\033[31m📊 当前使用率：${DISK_USAGE}%  |  阈值：${THRESHOLD}%\033[0m"
    echo -e "\033[31m💡 请及时清理无用文件，避免服务异常！\033[0m"
    echo -e "\033[31m===============================================================\033[0m"
fi
